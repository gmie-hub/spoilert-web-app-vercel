// Conversation ids must match the mobile app's ChatUtils.generateConversationId
// byte for byte, or web and mobile users would end up in different threads:
// sort the two user ids, join them with "_", SHA-256 the result and keep the
// first 16 hex characters behind a "conv_" prefix.
//
// SHA-256 is computed here rather than with crypto.subtle because subtle is
// async and only exists on secure origins (it is undefined over plain http on a
// LAN address), and lists need many ids synchronously.

